-- =====================================================================
-- Flask app setup: sequences for inserts from the web app + login table
-- Run after 01_schema_and_data.sql, in the same schema.
-- =====================================================================

SET DEFINE OFF

BEGIN EXECUTE IMMEDIATE 'DROP TABLE app_user PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE seq_zone';    EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE seq_bin';     EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE seq_vehicle'; EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE seq_worker';  EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE seq_station'; EXCEPTION WHEN OTHERS THEN NULL; END;
/

-- Start each sequence after the ids used by the mock data
CREATE SEQUENCE seq_zone    START WITH 10 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE seq_bin     START WITH 31 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE seq_vehicle START WITH 6  INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE seq_worker  START WITH 9  INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE seq_station START WITH 4  INCREMENT BY 1 NOCACHE;

-- Application accounts (passwords are stored as hashes, created by "flask seed-users")
CREATE TABLE app_user (
  user_id       NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY
                              CONSTRAINT pk_app_user PRIMARY KEY,
  username      VARCHAR2(50)  NOT NULL CONSTRAINT uq_app_user_name UNIQUE,
  password_hash VARCHAR2(255) NOT NULL,
  full_name     VARCHAR2(100) NOT NULL,
  role          VARCHAR2(12)  NOT NULL
                CONSTRAINT ck_app_user_role CHECK (role IN ('admin','supervisor','worker')),
  worker_id     NUMBER(10)    CONSTRAINT fk_app_user_worker REFERENCES worker (worker_id),
  CONSTRAINT ck_app_user_worker CHECK (role <> 'worker' OR worker_id IS NOT NULL)
);

COMMIT;
